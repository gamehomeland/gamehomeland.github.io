import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { createHash } from 'node:crypto';
const root = new URL('../', import.meta.url);
const load = async (name) => JSON.parse(await readFile(new URL('data/' + name, root), 'utf8'));
const [palette, profiles, support, manifest] = await Promise.all(
  [
    'furniture_palette.json',
    'client_color_profiles.json',
    'support_geometry.json',
    'client_palette_manifest.json',
  ].map(load),
);
for (const [name, expected] of Object.entries(manifest.generated)) {
  const actual = createHash('sha256')
    .update(await readFile(new URL('data/' + name, root)))
    .digest('hex');
  if (actual !== expected) throw new Error('资料校验失败：' + name);
}
if (palette.colors.length !== 72 || profiles.client_version !== palette.clientVersion)
  throw new Error('资料版本不一致');
const compact = palette.colors.map(({ key, rgb, translucent, alpha, variants }) => ({
  key,
  rgb,
  translucent,
  alpha,
  variants,
}));
const body =
  '// Generated by scripts/build-catalog.mjs; edit data sources instead.\n' +
  'export const catalogData = ' +
  JSON.stringify({
    version: palette.clientVersion,
    colors: compact,
    tables: profiles.tables,
    neutralKeys: profiles.neutral_keys,
    overlayKey: profiles.overlay_key,
    maxRecipeLayers: profiles.max_recipe_layers,
    support: support.runtime,
  }) +
  ';\n';
await mkdir(new URL('packages/core/src/', root), { recursive: true });
await writeFile(new URL('packages/core/src/catalog.generated.ts', root), body);
const experimental = await load('experimental_materials.json');
const editor = await load('editor_catalog.json');
const land = await load('land_catalog.json');
const basement = await load('basement_models.json');
const blueprintResources = await load('blueprint_resources.json');
await writeFile(
  new URL('packages/core/src/blueprint-resources.generated.ts', root),
  '// Generated by scripts/build-catalog.mjs.\nexport const blueprintResourceData = ' +
    JSON.stringify(blueprintResources) +
    ';\n',
);
if (
  basement.schemaVersion !== 1 ||
  basement.resources.length !== 6 ||
  basement.resources.some((r) => r.variants.length !== 24)
)
  throw new Error('地下室模型目录无效');
await writeFile(
  new URL('packages/core/src/basement-models.generated.ts', root),
  '// Generated by scripts/build-catalog.mjs.\nexport const basementModelData = ' +
    JSON.stringify(basement) +
    ';\n',
);
if (land.schemaVersion !== 1 || !land.presets.length || !land.maps.length)
  throw new Error('地块资料无效');
await writeFile(
  new URL('packages/core/src/land-catalog.generated.ts', root),
  '// Generated by scripts/build-catalog.mjs.\nexport const landCatalogData = ' +
    JSON.stringify(land) +
    ';\n',
);
if (editor.schemaVersion !== 1 || editor.resources.length < 1) throw new Error('编辑家具目录无效');
await writeFile(
  new URL('packages/core/src/editor-catalog.generated.ts', root),
  '// Generated by scripts/build-catalog.mjs.\nexport const editorCatalogData = ' +
    JSON.stringify(editor) +
    ';\n',
);
for (const [path, expected] of [
  ['docs/material-candidates.json', experimental.researchSha256],
  ['data/furniture_palette.json', experimental.paletteSha256],
]) {
  const actual = createHash('sha256')
    .update(await readFile(new URL(path, root)))
    .digest('hex');
  if (actual !== expected) throw new Error('试验资料校验失败：' + path);
}
if (experimental.defaultEnabled !== false || experimental.materials.length !== 6)
  throw new Error('试验色卡范围异常');
await writeFile(
  new URL('packages/core/src/experimental.generated.ts', root),
  '// Generated by scripts/build-catalog.mjs.\nexport const experimentalData = ' +
    JSON.stringify(experimental) +
    ';\n',
);
console.log(
  `家具资料：${palette.colors.length} 色、${compact.reduce((n, c) => n + c.variants.length, 0)} 规格、${Object.keys(profiles.tables.wall.colors).length} 配方`,
);
